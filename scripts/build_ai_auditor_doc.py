def add_callout(doc, title, body, fill="E8EEF5", color="0B2545"):
    table = doc.add_table(rows=1, cols=1)
    set_table_width(table, [6.3])
    cell = table.cell(0, 0)
    set_cell_shading(cell, fill)
    set_cell_border(cell, color="FFFFFF", size="0")
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(title)
    set_run_font(r, size=11, color=color, bold=True)
    p2 = cell.add_paragraph()
    p2.paragraph_format.space_after = Pt(4)
    p2.paragraph_format.line_spacing = 1.10
    r2 = p2.add_run(body)
    set_run_font(r2, size=10.5, color=COLORS["ink"])
    add_p(doc, after=2)


def add_kv_table(doc, rows, widths=(1.65, 4.65), header=None):
    table = doc.add_table(rows=0, cols=2)
    set_table_width(table, widths)
    if header:
        row = table.add_row()
        row.cells[0].merge(row.cells[1])
        set_cell_shading(row.cells[0], COLORS["light_blue"])
        p = row.cells[0].paragraphs[0]
        r = p.add_run(header)
        set_run_font(r, size=10.5, bold=True, color=COLORS["navy"])
    for label, value in rows:
        cells = table.add_row().cells
        set_cell_shading(cells[0], COLORS["light_gray"])
        p = cells[0].paragraphs[0]
        r = p.add_run(label)
        set_run_font(r, size=9.5, bold=True, color=COLORS["dark_blue"])
        p2 = cells[1].paragraphs[0]
        p2.paragraph_format.line_spacing = 1.10
        r2 = p2.add_run(value)
        set_run_font(r2, size=9.5, color=COLORS["ink"])
    add_p(doc, after=3)
    return table


def add_table(doc, headers, rows, widths, header_fill="E8EEF5", font_size=9.2):
    table = doc.add_table(rows=1, cols=len(headers))
    set_table_width(table, widths)
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        set_cell_shading(hdr[i], header_fill)
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        set_run_font(r, size=9.2, bold=True, color=COLORS["navy"])
    for row_vals in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row_vals):
            p = cells[i].paragraphs[0]
            p.paragraph_format.line_spacing = 1.05
            if i == 0 and len(str(val)) <= 12:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(str(val))
            set_run_font(r, size=font_size, color=COLORS["ink"])
    add_p(doc, after=4)
    return table


def add_metric_strip(doc, metrics):
    table = doc.add_table(rows=1, cols=len(metrics))
    set_table_width(table, [6.3 / len(metrics)] * len(metrics))
    for cell, (num, label, fill) in zip(table.rows[0].cells, metrics):
        set_cell_shading(cell, fill)
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(num)
        set_run_font(r, size=15, bold=True, color=COLORS["navy"])
        p2 = cell.add_paragraph()
        p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(label)
        set_run_font(r2, size=8.5, color=COLORS["muted"])
    add_p(doc, after=5)


