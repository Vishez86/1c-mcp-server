// JS-порт ВТОРОГО ЭШЕЛОНА маскирования (MCP_Security.МаскироватьПоляДляLLMРекурсивно):
// определение типа строки, псевдонима строки и применение набора масок.
// Дополняет scripts/privacy_mask_marking_port.mjs, который моделирует ДРУГОЕ —
// разбор текста запроса и пометку колонок. R-8, R-9, R-10, R-12 и R-18 живут
// здесь, и без этой модели их проверить до деплоя нечем: компилятора 1С на
// стороне разработки нет.
//
//   node scripts/privacy_echelon_port.mjs
//
// Прогоняется в ДВУХ редакциях — до и после гейта, — потому что цена правки
// видна только сравнением: правка сужает маскирование, и надо доказать, что
// сужение попадает ровно в цель. Именно так найдено, что буквальное правило ТЗ
// («шаг только при пустом ТипРодителя») теряет кейс E3.
//
// Метаданные и политика — заглушки: модель проверяет ВЕТВЛЕНИЕ, а не разрешение
// имён живого контура. Живая приёмка обязательна.
const CLOSED = "Справочник.ЗакрытыйТип";
const REG_IN = "РегистрСведений.ЗакрытыйРегистр";     // есть в политике
const REG_OUT = "РегистрСведений.ЧужойРегистр";        // в политике НЕТ
const CAT_MASK = "Справочник.СМаскойКомментария";   // маски есть, Представление — НЕ реквизит
// Бисект расхождения `.2` → `.3` по родственникам (приёмка 07.08.2026).
// Подчинённый справочник персон: своей записи в политике НЕТ (черновик её только
// заводит), владелец — ссылка закрытого типа. Ровно та конфигурация, при которой
// строка на `.2` приходила закрытой, а на `.3` открытой.
const SUBORD = "Справочник.ПодчиненныйБезЗаписи";
// R-18: табличная часть настроенного типа в форме А — так её строит
// ПолноеИмяТабличнойЧастиPrivacy. Расхождение `.2` → `.3` по
// КонтактнаяИнформация.Представление (`Контр-скрыто` → открыто) локализовано
// вторым гейтом R-8, поставленным в #120 в ДВУХ местах вместо одного.
const TP_CLOSED = `${CLOSED}.ТабличнаяЧасть.КонтактнаяИнформация`;
// R-12: тип персон и подчинённый ему справочник — закрывается по факту
// подчинённости, без записи в политике.
const PERSON = "Справочник.ФизическиеЛица";
const PERSON_SUB = "Справочник.РодственникиФизическихЛиц";
const POLICY = {
  [CLOSED]: { alias: "Зкр-", fields: ["Наименование", "ИНН"] },
  [REG_IN]: { alias: "", fields: ["Серия", "Номер", "КемВыдан"] },
  [CAT_MASK]: { alias: "", fields: ["Комментарий"] },
  [PERSON]: { alias: "", person: true, fields: ["НаименованиеСлужебное", "ИНН"] },
};
// R-9: наследование там, где `Представление` объявлено полем метаданных.
// Заглушка сверена с живыми метаданными 06.08.2026 тем же набором коллекций,
// каким читает движок: у регистра Представление есть ресурсом, у справочника нет.
const HAS_PRESENTATION_FIELD = { [REG_IN]: true, [REG_OUT]: true };
// Владельцы подчинённых справочников — источник правила R-12.
const OWNERS = { [PERSON_SUB]: [PERSON], [SUBORD]: [CLOSED] };
const norm = (s) => String(s).toUpperCase().replace(/[\s_\-.]/g, "");
const entry = (t) => POLICY[t];
// MCP_Security.ЭтоТипФизическогоЛицаLLM — сверка по ПРЕФИКСУ нормализованного
// имени, под который подчинённый справочник не подходит: именно поэтому у
// родственников персональный псевдоним не присваивался (§4.14).
const isPersonType = (t) => norm(t).startsWith(norm("СправочникФизическиеЛица"));
// MCP_Security.ЭтоПодчиненныйТипуПерсонPrivacy (R-12)
const isPersonSub = (t) => !isPersonType(t) && (OWNERS[t] ?? []).some(isPersonType);
// MCP_Security.ЭтоТипПерсональногоНабораLLM
const isPersonSet = (t) => isPersonType(t) || isPersonSub(t);
// MCP_Security.ЭтоТабличнаяЧастьПоИмениPrivacy / ВладелецТабличнойЧастиПоИмениPrivacy
const isTabularPart = (t) => String(t).toUpperCase().includes(".ТАБЛИЧНАЯЧАСТЬ.");
const tabularOwner = (t) => {
  const at = String(t).toUpperCase().lastIndexOf(".ТАБЛИЧНАЯЧАСТЬ.");
  return at < 0 ? "" : String(t).slice(0, at);
};
// MCP_Security.ТипВЗакрытомНабореPrivacy
const typeInClosedSet = (t) => Boolean(t) && !isTabularPart(t)
  && (Boolean(entry(t)) || isPersonSet(t));
// R-15: набор ФИО правилом, а не перечнем. МестоРождения не входит — §6.6.
const FIO = new Set(["Фамилия", "Имя", "Отчество", "ФИО", "Инициалы",
  "НаименованиеСлужебное", "УточнениеНаименования"].map(norm));
// R-13, ограничитель 4 (классы 4a…4d) — сокращённый до кейсов порта.
const CORE_WHITELIST = new Set(["Код", "Тип", "Вид", "ВидДляСписка", "НомерСтроки",
  "НаименованиеБанка", "НаименованиеОКВЭД", "МестоРожденияПредставление"].map(norm));
// R-11: классификаторы строки табличной части остаются открытыми.
const TP_CLASSIFIERS = new Set(["Тип", "Вид", "ВидДляСписка", "НомерСтроки"].map(norm));
// MCP_Security.ПолеВЯдреИдентификацииPrivacy (R-13). Точное «Представление»
// ядром не берётся — его решает наследование R-9.
const inCore = (t, f) => {
  const n = norm(f);
  if (!n || n === norm("Представление")) return false;
  if (!n.includes(norm("Наименование")) && !n.includes(norm("Представление"))) return false;
  if (CORE_WHITELIST.has(n)) return false;
  return typeInClosedSet(t);
};
// MCP_Config: mask_presentation включается АВТОМАТИЧЕСКИ, когда в fields записи
// есть поле имени объекта. Без этого признака порт считал Представление типа с
// псевдонимом открытым и давал ложный провал на R-18.
const NAME_LIKE = new Set(["Наименование", "НаименованиеПолное", "ПолноеНаименование",
  "КраткоеНаименование", "Код", "Представление"].map(norm));
const maskPresentation = (t) => Boolean(entry(t)?.fields.some((x) => NAME_LIKE.has(norm(x))));
// insideTabular — рекурсия идёт по данным табличной части (ключ tabular_sections
// либо табличный тип строки). Второй эшелон решает это по ПУТИ, и без параметра
// порт не различал бы строку ТЧ, заимствовавшую тип у ссылки владельца.
const fieldClosed = (t, f, insideTabular = false) => {
  // R-11: поле строки табличной части закрытого типа. Тип строки бывает как
  // самой ТЧ (шаг 5), так и заимствованным у ссылки владельца (шаг 4, R-18) —
  // закрывать обязаны обе формы, иначе адрес уходит из-за состава колонок.
  if (isTabularPart(t) || insideTabular) {
    if (TP_CLASSIFIERS.has(norm(f))) return false;
    return typeInClosedSet(isTabularPart(t) ? tabularOwner(t) : t);
  }
  // R-12 + R-15: подчинённый персоне наследует набор владельца, ФИО — правилом.
  if (isPersonSet(t)) {
    if (FIO.has(norm(f))) return true;
    for (const owner of [t, ...(OWNERS[t] ?? [])]) {
      const p = entry(owner);
      if (p && p.fields.some((x) => norm(x) === norm(f))) return true;
    }
  }
  if (inCore(t, f)) return true;
  const p = entry(t); if (!p) return false;
  if (p.fields.some((x) => norm(x) === norm(f))) return true;
  if (norm(f) === norm("Представление") && maskPresentation(t)) return true;
  // R-9 (уточнено ревью): наследует только когда Представление существует у типа
  // как реквизит/ресурс. Иначе признак был бы константой «любой тип из масок».
  return ["ПРЕДСТАВЛЕНИЕ", "PRESENTATION"].includes(norm(f))
    && p.fields.length > 0 && Boolean(HAS_PRESENTATION_FIELD[t]);
};
// ТипОбъектаДляМаскированияLLM: шаги 1 (свои type+uuid) → 2 (register в значении)
// → 3 (ref/target/item) → 4 (любая ссылка типа из политики) → ТипРодителя.
// Возвращает {тип, шаг} — шаг обязателен для бисекта: вердикт «закрыто/открыто»
// не говорит, ГДЕ разошлись редакции, а «шаг 4 против шага 5» говорит.
function rowType(value, parentType, gated, insideTabular = false) {
  if (value?.type && value?.uuid) return { тип: value.type, шаг: 1 };
  if (typeof value?.register === "string" && value.register.includes("."))
    return { тип: value.register, шаг: 2 };
  for (const k of ["ref", "target", "item"]) {
    const r = value?.[k];
    if (r?.type && r?.uuid) return { тип: r.type, шаг: 3 };
  }
  // шаг 4 — тот самый, который R-8 закрывает гейтом
  // Гейт R-8: шаг 4 пропускается, только если у родителя ЕСТЬ своя запись
  // в политике. Родитель без записи продолжает заимствовать тип у ссылки —
  // иначе терялось бы маскирование его собственных колонок (кейс E3).
  // R-18: строку табличной части гейт пропускает всегда — ссылка владельца в
  // строке его же ТЧ не «чужой объект», от которого гейт защищал.
  if (!gated || insideTabular || !parentType || !entry(parentType)) {
    for (const v of Object.values(value ?? {})) {
      if (v && typeof v === "object" && v.type && v.uuid && entry(v.type))
        return { тип: v.type, шаг: 4 };
    }
  }
  return { тип: parentType, шаг: 5 };
}
// ПсевдонимТипаДляОбъекта — второй гейт R-8 (MCP_Security.bsl, ~:873). Именно он
// заглушал `Контр-скрыто` у строки ТЧ настроенного типа: собственных type/uuid у
// такой строки нет, и без заимствования псевдоним ей взять неоткуда.
function rowAlias(value, parentAlias, parentType, gated, insideTabular = false) {
  if (value?.type && value?.uuid) return entry(value.type)?.alias ?? "";
  if (!gated || insideTabular || !parentType || !entry(parentType)) {
    for (const v of Object.values(value ?? {})) {
      if (v && typeof v === "object" && v.type && v.uuid && entry(v.type))
        return entry(v.type).alias ? entry(v.type).alias + "скрыто" : "";
    }
  }
  return parentAlias;
}
// R-10: вердикт первого эшелона применяется ПО КОЛОНКЕ, а не по имени ключа.
// Подавляет только маскировщики по имени и только на плоских значениях: ссылку
// первый эшелон намеренно не метит (M-03.1), её закрывает псевдонимизация.
function openedByFirstEchelon(value, key, decisions) {
  if (!decisions) return false;
  if (value && typeof value === "object") return false;
  const verdict = decisions[String(key).toUpperCase()];
  return verdict === false;
}
function maskRow(row, parentType, gated, opts = {}) {
  const insideTabular = Boolean(opts.insideTabular) || isTabularPart(parentType);
  const { тип: t, шаг } = rowType(row, parentType, gated, insideTabular);
  const alias = rowAlias(row, opts.parentAlias ?? "", parentType, gated, insideTabular);
  const out = {};
  for (const [k, v] of Object.entries(row)) {
    if (v && typeof v === "object" && v.type && v.uuid) {
      // Ссылка: маскируется по СВОИМ type/uuid — шаг 1 рекурсии.
      out[k] = entry(v.type)
        ? { ...v, presentation: (entry(v.type).alias || "XXXXXXX") + (entry(v.type).alias ? "КОД" : "") }
        : v;
      continue;
    }
    if (openedByFirstEchelon(v, k, opts.decisions)) { out[k] = v; continue; }
    if (!fieldClosed(t, k, insideTabular)) { out[k] = v; continue; }
    // Имя-подобное поле получает псевдоним строки, если он есть, иначе маску
    // (МаскаПоляТипаДляLLM). Прочие поля — всегда маска.
    const nameLike = ["Наименование", "Представление", "Код", "НаименованиеПолное"].map(norm);
    out[k] = (alias && nameLike.includes(norm(k))) ? alias : "XXXXXXX";
  }
  return { тип: t, шаг, псевдоним: alias, строка: out };
}
