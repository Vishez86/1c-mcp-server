// JS-порт ВТОРОГО ЭШЕЛОНА маскирования (MCP_Security.МаскироватьПоляДляLLMРекурсивно):
// определение типа строки, псевдонима строки и применение набора масок.
// Дополняет scripts/privacy_mask_marking_port.mjs, который моделирует ДРУГОЕ —
// разбор текста запроса и пометку колонок. R-8 и R-9 живут здесь, и без этой
// модели их проверить до деплоя нечем: компилятора 1С на стороне разработки нет.
//
//   node scripts/privacy_echelon_port.mjs
//
// Прогоняется в ДВУХ редакциях — до и после гейта, — потому что цена правки
// видна только сравнением: правка сужает маскирование, и надо доказать, что
// сужение попадает ровно в цель. Именно так найдено, что буквальное правило ТЗ
// («шаг только при пустом ТипРодителя») теряет кейс E3.
//
// Метаданные и политика — заглушки: модель проверяет ВЕТВЛЕНИЕ, а не разрешение
// имён живого контура. Живая приёмка обязательна.
const CLOSED = "Справочник.ЗакрытыйТип";
const REG_IN = "РегистрСведений.ЗакрытыйРегистр";     // есть в политике
const REG_OUT = "РегистрСведений.ЧужойРегистр";        // в политике НЕТ
const CAT_MASK = "Справочник.СМаскойКомментария";   // маски есть, Представление — НЕ реквизит
const POLICY = {
  [CLOSED]: { alias: "Зкр-", fields: ["Наименование", "ИНН"] },
  [REG_IN]: { alias: "", fields: ["Серия", "Номер", "КемВыдан"] },
  [CAT_MASK]: { alias: "", fields: ["Комментарий"] },
};
// Есть ли Представление у типа как РЕАЛЬНОЕ поле метаданных (реквизит/ресурс).
// У регистра сведений — да, у справочника — нет (там это имя объекта).
const HAS_PRESENTATION_FIELD = { [REG_IN]: true, [REG_OUT]: true };
const norm = (s) => String(s).toUpperCase().replace(/[\s_\-.]/g, "");
const entry = (t) => POLICY[t];
const fieldClosed = (t, f) => {
  const p = entry(t); if (!p) return false;
  if (p.fields.some((x) => norm(x) === norm(f))) return true;
  // R-9 (уточнено ревью): наследует только когда Представление существует у типа
  // как реквизит/ресурс. Иначе признак был бы константой «любой тип из масок».
  return ["ПРЕДСТАВЛЕНИЕ", "PRESENTATION"].includes(norm(f))
    && p.fields.length > 0 && Boolean(HAS_PRESENTATION_FIELD[t]);
};
// ТипОбъектаДляМаскированияLLM: шаги 1 (свои type+uuid) → 2 (register в значении)
// → 3 (ref/target/item) → 4 (любая ссылка типа из политики) → ТипРодителя.
function rowType(value, parentType, gated) {
  if (value?.type && value?.uuid) return value.type;                      // шаг 1
  if (typeof value?.register === "string" && value.register.includes(".")) return value.register; // шаг 2
  for (const k of ["ref", "target", "item"]) {
    const r = value?.[k];
    if (r?.type && r?.uuid) return r.type;                                // шаг 3
  }
  // шаг 4 — тот самый, который R-8 закрывает гейтом
  // Гейт R-8: шаг 4 пропускается, только если у родителя ЕСТЬ своя запись
  // в политике. Родитель без записи продолжает заимствовать тип у ссылки —
  // иначе терялось бы маскирование его собственных колонок (кейс E3).
  if (!gated || !parentType || !entry(parentType)) {
    for (const v of Object.values(value ?? {})) {
      if (v && typeof v === "object" && v.type && v.uuid && entry(v.type)) return v.type;
    }
  }
  return parentType;
}
function maskRow(row, parentType, gated) {
  const t = rowType(row, parentType, gated);
  const out = {};
  for (const [k, v] of Object.entries(row)) {
    if (v && typeof v === "object" && v.type && v.uuid) {
      // Ссылка: маскируется по СВОИМ type/uuid — шаг 1 рекурсии.
      out[k] = entry(v.type)
        ? { ...v, presentation: (entry(v.type).alias || "XXXXXXX") + (entry(v.type).alias ? "КОД" : "") }
        : v;
      continue;
    }
    out[k] = fieldClosed(t, k) ? "XXXXXXX" : v;
  }
  return { тип: t, строка: out };
}
const кейсы = [
  ["E1 регистр В политике + ссылка закрытого типа: набор РЕГИСТРА (цель R-8)",
    { Серия: "с", Номер: "н", Физлицо: { type: CLOSED, uuid: "u", presentation: "имя" } }, REG_IN,
    (r) => r.строка.Серия === "XXXXXXX" && r.строка.Номер === "XXXXXXX"],
  ["E2 та же строка: ссылка подменена по своим type/uuid",
    { Серия: "с", Физлицо: { type: CLOSED, uuid: "u", presentation: "имя" } }, REG_IN,
    (r) => String(r.строка.Физлицо.presentation).startsWith("Зкр-")],
  ["E3 регистр ВНЕ политики + ссылка закрытого типа + своя колонка ИНН",
    { ИНН: "123", Контрагент: { type: CLOSED, uuid: "u", presentation: "имя" } }, REG_OUT,
    (r) => r.строка.ИНН === "XXXXXXX"],
  ["E4 строка run_1c_query (родителя нет): шаг 4 работает",
    { Наименование: "имя", Ссылка: { type: CLOSED, uuid: "u", presentation: "п" } }, "",
    (r) => r.строка.Наименование === "XXXXXXX"],
  ["E5 R-9: Представление строки регистра из политики",
    { Представление: "серия номер кем выдан", Серия: "с" }, REG_IN,
    (r) => r.строка.Представление === "XXXXXXX"],
  ["E6 парная: Представление строки регистра ВНЕ политики — открыто",
    { Представление: "текст" }, REG_OUT,
    (r) => r.строка.Представление === "текст"],
  ["E7 находка 1: Представление СПРАВОЧНИКА с маской Комментарий — ОТКРЫТО",
    { Представление: "имя объекта", Комментарий: "к" }, CAT_MASK,
    (r) => r.строка.Представление === "имя объекта" && r.строка.Комментарий === "XXXXXXX"],
  ["E8 находка 1 парная: Представление РЕГИСТРА из политики — закрыто",
    { Представление: "серия номер", Серия: "с" }, REG_IN,
    (r) => r.строка.Представление === "XXXXXXX"],
];
let провалов = 0;
for (const режим of [false, true]) {
  console.log(`\n===== ${режим ? "ПОСЛЕ R-8 (гейт по пустому ТипРодителя)" : "ДО R-8 (текущий .2)"} =====`);
  for (const [имя, строка, родитель, ждём] of кейсы) {
    const r = maskRow(строка, родитель, режим);
    const ok = ждём(r);
    console.log(`${ok ? "выполнено   " : "НЕ выполнено"} | ${имя}\n              тип строки: ${r.тип || "(пусто)"}`);
  }
}

console.log(`
Итог второго эшелона: провалов в редакции «после» — ${провалов}`);
process.exitCode = провалов > 0 ? 1 : 0;
