#!/usr/bin/env node
// Общие правила подбора фикстур для проверок, работающих на живой базе.
//
// Единственный источник этих правил на все скрипты: до него `mcp_deploy_smoke.mjs`
// знал про служебные объекты MCP, а контракт-тест — нет, и одна и та же ловушка
// была закрыта в одном месте и открыта в другом (ТЗ-2 R-1).
//
// Общий принцип: фикстура выбирается ПО СОСТАВУ, а не по порядку в списке и не по
// наличию одного поля. Слабый признак «первый по алфавиту» садится не туда на
// каждой второй конфигурации, и приёмка тратит основное время на разбор провалов,
// ни один из которых не является дефектом сервера.

// Служебные объекты самого MCP-сервера (MCP_Маскирование, MCP_ПравовыеИсточники и
// т.п.) фикстурами быть НЕ МОГУТ.
//
// Их имена смешанного алфавита — латинское «MCP_» плюс кириллица, — и до ревизии
// 2026-08-17.1 правило антиомоглифа `temporary_table_identifier_mixed_script`
// блокировало ЛЮБОЙ запрос к ним, ещё до проверки полей: у M, C и P есть
// кириллические двойники, а белый список правила требовал хотя бы одну букву без
// двойника. Латиница сортируется раньше кириллицы, поэтому такой объект
// оказывался ПЕРВЫМ в discovery и забирал фикстуру — отсюда 7 ложных провалов
// контракт-теста на каждом контуре и ещё 10 каскадом на ZUP, где та же фикстура
// служила источником sampleRef и seed для примеров запросов (#145).
//
// Ложное срабатывание закрыто снятием правила с сервера (класс «стиль» судит
// внешний чекер, решение 13.08). Исключение служебных объектов из фикстур
// остаётся правильным и после его починки: проверять контракт на объекте самого
// сервера — значит проверять сервер собой же.
export const СЛУЖЕБНЫЙ_ПРЕФИКС = /(^|\.)MCP_/u;

export const служебныйОбъект = (fullName) => СЛУЖЕБНЫЙ_ПРЕФИКС.test(String(fullName ?? ""));

// Ресурсы регистра бухгалтерии, выведенные из состава его виртуальных таблиц.
//
// Нужны, чтобы ожидания теста не содержали захардкоженных имён: ПР (постоянные
// разницы) — атрибут налогового учёта, а не регистра бухгалтерии вообще. На ERP
// первый регистр с СуммаОстаток — «Международный», у которого ресурса СуммаПР нет
// и быть не должно, а тест требовал СуммаПРОборотДт безусловно (#146).
//
// Возвращает Set суффиксов X таких, что в ОборотыДтКт есть Сумма<X>ОборотДт и
// Сумма<X>ОборотКт. Пустая строка в наборе означает базовый СуммаОборотДт/Кт.
export function суффиксыСуммовыхРесурсов(виртуальныеТаблицы) {
  const дтКт = (виртуальныеТаблицы ?? []).find((v) => v?.name === "ОборотыДтКт");
  const поля = new Set(дтКт?.common_fields ?? []);
  const суффиксы = new Set();
  for (const поле of поля) {
    const m = /^Сумма(.*)ОборотДт$/u.exec(поле);
    if (!m) continue;
    if (поля.has(`Сумма${m[1]}ОборотКт`)) суффиксы.add(m[1]);
  }
  return суффиксы;
}

// Подбор регистра бухгалтерии ПО СОСТАВУ: подходит тот, чьи ВТ покрывают все
// требуемые кейсом ресурсы. Прежний критерий — «первый, у кого есть СуммаОстаток» —
// слабее требований кейсов, и на ERP давал регистр без ПР-ресурсов.
//
// Возвращает Неопределено (null), если подходящего нет: кейс обязан пометиться
// skipped с указанием причины, а не упасть. Провал по непригодной фикстуре —
// не сигнал о сервере.
export async function подобратьРегистрБухгалтерии({
  списокОбъектов,
  структураОбъекта,
  требуемыеСуффиксы = [],
  требуемыеПоляОстатков = [],
  // Парный суффикс (НУ/ПР/ВР, валютные ресурсы) ПРЕДПОЧИТАЕТСЯ, но не требуется:
  // регистр без таких ресурсов публикует у ОборотыДтКт одну СуммаОборот без
  // раздельных Дт/Кт — это норма конфигурации, а не дефект. Требование сделало бы
  // фикстуру ненаходимой на конфигурациях без налогового учёта и превратило бы
  // все регистровые кейсы в skipped.
  предпочестьПарныйСуффикс = false,
  максимумКандидатов = 8,
}) {
  const кандидаты = (await списокОбъектов()).filter((o) => o?.full_name && !служебныйОбъект(o.full_name));
  let запасной = null;

  for (const item of кандидаты.slice(0, максимумКандидатов)) {
    const структура = await структураОбъекта(item.full_name);
    const вт = структура?.metadata?.register_schema?.virtual_tables ?? [];
    if (вт.length === 0) continue;

    const остатки = вт.find((v) => v?.name === "Остатки")?.common_fields ?? [];
    const суффиксы = суффиксыСуммовыхРесурсов(вт);
    const [, имяИзFullName = ""] = item.full_name.split(".");
    const кандидат = {
      fullName: item.full_name,
      name: item.name || имяИзFullName,
      виртуальныеТаблицы: вт,
      суффиксы,
      остатки,
    };

    if (!требуемыеПоляОстатков.every((f) => остатки.includes(f))) continue;
    if (!требуемыеСуффиксы.every((s) => суффиксы.has(s))) continue;
    запасной = запасной ?? кандидат;
    if (!предпочестьПарныйСуффикс || [...суффиксы].some((s) => s !== "")) return кандидат;
  }

  return запасной;
}
