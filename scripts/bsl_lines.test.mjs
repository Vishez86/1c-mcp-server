#!/usr/bin/env node
// Порт-тесты общего сканера BSL (ТЗ-1 R-7). Живой контур не нужен.
//
// Два кейса обязательны по ТЗ и держат правку с ДВУХ сторон:
//   • многострочный литерал с «|», содержащий ключевые слова и кавычку, не
//     должен давать ни ложных токенов, ни ложного «кавычки не закрыты»;
//   • НАСТОЯЩАЯ незакрытая кавычка обязана остаться провалом — без этого
//     кейса послабление ради «|» превращает ворота в вечнозелёные, а это
//     ровно тот исход, против которого заведены #143/#144.
//
// Запуск: node scripts/bsl_lines.test.mjs

import { scanBsl } from "./bsl_lines.mjs";

let failed = 0;
function check(name, ok, detail = "") {
  if (!ok) failed += 1;
  console.log(`  ${ok ? "✔" : "✘"} ${name}${ok || !detail ? "" : ` — ${detail}`}`);
}

// ── 1. Многострочный литерал: ключевые слова внутри не считаются кодом ──────
{
  const src = [
    'Функция Т()',
    '\tТекст = "ВЫБРАТЬ * ИЗ Справочник.Тест',
    '\t\t|ГДЕ ЕСЛИ ДЛЯ ПОКА ПОПЫТКА КОНЕЦЕСЛИ',
    '\t\t|И Поле = ""значение"" // это не комментарий',
    '\t\t|";',
    '\tВозврат Текст;',
    'КонецФункции',
  ].join("\n");
  const { clean, cleanLines, unclosed } = scanBsl(src);

  check("многострочный литерал закрыт", unclosed.length === 0, `unclosed: ${unclosed.join(", ")}`);
  check("ключевые слова из литерала не попали в код",
    !/ЕСЛИ|ПОКА|ПОПЫТКА|ГДЕ/.test(clean), clean.replace(/\n/g, "⏎"));
  check("число строк сохранено", cleanLines.length === 7, `${cleanLines.length} вместо 7`);
  check("код вокруг литерала уцелел",
    /Функция Т\(\)/.test(clean) && /Возврат Текст;/.test(clean) && /КонецФункции/.test(clean));
  check("кавычки сохранены (арность вызовов не ломается)",
    (clean.match(/"/g) || []).length === 2, `кавычек: ${(clean.match(/"/g) || []).length}`);
}

// ── 2. НАСТОЯЩАЯ незакрытая кавычка — обязан быть провал ────────────────────
{
  const src = [
    'Функция Т()',
    '\tТекст = "начали и не закрыли;',
    '\tВозврат Текст;',
    'КонецФункции',
  ].join("\n");
  const { unclosed } = scanBsl(src);
  check("незакрытая кавычка поймана", unclosed.length === 1, `unclosed: ${unclosed.join(", ")}`);
  check("указана строка открытия литерала", unclosed[0] === 2, `строка ${unclosed[0]} вместо 2`);
}

// ── 3. Незакрытый литерал в конце файла ─────────────────────────────────────
{
  const { unclosed } = scanBsl('Текст = "хвост файла');
  check("незакрытый литерал в конце файла пойман", unclosed.length === 1 && unclosed[0] === 1);
}

// ── 4. Кавычка внутри комментария литерал не открывает ──────────────────────
// Прежние копии сканера снимали комментарии ПОСЛЕ разбора кавычек, поэтому
// комментарий с нечётным числом кавычек давал ложный провал.
{
  const src = [
    'Функция Т()',
    '\t// платформа отвечает «Ожидается символ "',
    '\tВозврат 1;',
    'КонецФункции',
  ].join("\n");
  const { clean, unclosed } = scanBsl(src);
  check("кавычка в комментарии не открывает литерал", unclosed.length === 0,
    `unclosed: ${unclosed.join(", ")}`);
  check("комментарий снят", !/Ожидается/.test(clean));
}

// ── 5. Удвоенная кавычка внутри однострочного литерала ──────────────────────
{
  const { clean, unclosed } = scanBsl('Т = "он сказал ""да"" и ушёл"; Ф(Т);');
  check("удвоенная кавычка не закрывает литерал", unclosed.length === 0);
  check("код после литерала виден", /Ф\(Т\);/.test(clean), clean);
}

// ── 6. Пустая строка внутри многострочного литерала ─────────────────────────
{
  const src = ['Т = "первая', '', '|вторая";'].join("\n");
  const { unclosed } = scanBsl(src);
  check("пустая строка не прерывает литерал", unclosed.length === 0, `unclosed: ${unclosed.join(", ")}`);
}

// ── 7. Литерал закрывается в середине строки продолжения ────────────────────
{
  const src = ['Т = "начало', '|конец" + Суффикс;'].join("\n");
  const { clean, unclosed } = scanBsl(src);
  check("код после закрытия на строке продолжения виден",
    unclosed.length === 0 && /\+ Суффикс;/.test(clean), clean.replace(/\n/g, "⏎"));
}

console.log(failed === 0 ? "\n  ✔ порт-тесты сканера пройдены" : `\n  ✘ провалов: ${failed}`);
process.exit(failed === 0 ? 0 : 1);
